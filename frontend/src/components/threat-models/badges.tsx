import { CircleCheck, FilePen, ListChecks, Sparkles, UserRound } from "lucide-react"

import type { ThreatSource, VersionSummary } from "@/lib/threat-models"
import { cn } from "@/lib/utils"

export const CHIP = "inline-flex h-6 items-center gap-1.5 rounded-md border px-2 text-xs font-medium whitespace-nowrap"

/** Draft or approved, as icon + text (never colour alone, NFR-4.3). */
export function VersionStatus({ version }: { version: Pick<VersionSummary, "status"> }) {
  if (version.status === "approved") {
    return (
      <span className={cn(CHIP, "border-success/40 text-success")}>
        <CircleCheck className="size-3.5" aria-hidden="true" />
        Approved
      </span>
    )
  }
  return (
    <span className={cn(CHIP, "border-dashed border-warning/60 text-warning")}>
      <FilePen className="size-3.5" aria-hidden="true" />
      Draft
    </span>
  )
}

/** NFR-9.4: content generated by an LLM is labelled as such until a person has approved it. */
export function AiGeneratedLabel({ note }: { note?: string }) {
  return (
    <span className={cn(CHIP, "border-confirm/50 bg-confirm/10 text-confirm")}>
      <Sparkles className="size-3.5" aria-hidden="true" />
      AI-generated
      {note && <span className="font-normal">({note})</span>}
    </span>
  )
}

const SOURCE = {
  baseline: { icon: ListChecks, label: "Baseline rule", style: "border-border-strong text-text-secondary" },
  ai_suggested: { icon: Sparkles, label: "AI-suggested", style: "border-confirm/50 text-confirm" },
  analyst: { icon: UserRound, label: "Added by a person", style: "border-primary/40 text-link" },
} as const

/** Where a threat comes from (UC-3.1 steps 3-4, UC-3.2 step 3). */
export function SourceChip({ source }: { source: ThreatSource }) {
  const { icon: Icon, label, style } = SOURCE[source]
  return (
    <span className={cn(CHIP, style)}>
      <Icon className="size-3.5" aria-hidden="true" />
      {label}
    </span>
  )
}
