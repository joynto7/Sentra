"use client"

import { useCallback, useEffect, useState } from "react"
import { Download, Loader } from "lucide-react"
import { toast } from "sonner"

import { EmptyState } from "@/components/layout/empty-state"
import { PageHeader } from "@/components/layout/page-header"
import { ReportDialog } from "@/components/reports/report-dialog"
import { Alert, AlertDescription } from "@/components/ui/alert"
import { Button } from "@/components/ui/button"
import {
  Dialog,
  DialogClose,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog"
import { Skeleton } from "@/components/ui/skeleton"
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from "@/components/ui/table"
import { Tabs, TabsContent, TabsList, TabsTrigger } from "@/components/ui/tabs"
import { Tooltip, TooltipContent, TooltipTrigger } from "@/components/ui/tooltip"
import { ApiError } from "@/lib/api"
import { useCan } from "@/lib/permissions"
import {
  FREQUENCY_LABEL,
  type Report,
  type ReportList,
  STATUS_LABEL,
  type Schedule,
  TYPE_LABEL,
  changeSchedule,
  deleteSchedule,
  downloadUrl,
  listReports,
  runSchedule,
} from "@/lib/reports"
import { formatDate, formatDateTime } from "@/lib/targets"
import { cn } from "@/lib/utils"

const POLL = 2000

const STATUS_STYLE: Record<string, string> = {
  ready: "border-success/40 text-success",
  generating: "border-primary/50 text-primary",
  empty: "border-border-strong text-muted-foreground",
  failed: "border-destructive/50 text-destructive",
}

/** The state of a report, in words and never in colour alone (NFR-4.3). */
function StatusChip({ report }: { report: Report }) {
  return (
    <span
      className={cn(
        "inline-flex h-6 items-center gap-1.5 rounded-md border px-2 text-xs font-medium whitespace-nowrap",
        STATUS_STYLE[report.status],
      )}
    >
      {report.status === "generating" && (
        <Loader className="size-3.5 animate-spin" aria-hidden="true" />
      )}
      {STATUS_LABEL[report.status]}
    </span>
  )
}

function scopeText(report: Report | Schedule): string {
  if ("campaign_run" in report && report.campaign_run) return `Campaign run ${report.campaign_run}`
  if (report.target) return report.target
  return report.category ? `All targets · ${report.category}` : "All targets"
}

/**
 * Screen 52 (UC-9.1, UC-9.2): the reports the organization has, and the schedules that produce
 * them. A report that is being written says so and the page follows it; one that found nothing
 * says that instead of offering a file; a ready one offers the download with its checksum.
 */
export function ReportsPage() {
  const canGenerate = useCan("generate_reports")
  const [data, setData] = useState<ReportList | null>(null)
  const [error, setError] = useState(false)
  const [attempt, setAttempt] = useState(0)
  /** null while it is closed; a schedule to edit it (UC-9.2, 4a), `scheduled` to start as one. */
  const [dialog, setDialog] = useState<{
    schedule?: Schedule
    scheduled?: boolean
  } | null>(null)
  const [deleting, setDeleting] = useState<Schedule | null>(null)
  const [busy, setBusy] = useState<string | null>(null)

  useEffect(() => {
    const controller = new AbortController()
    listReports(controller.signal)
      .then((found) => {
        setData(found)
        setError(false)
      })
      .catch(() => !controller.signal.aborted && setError(true))
    return () => controller.abort()
  }, [attempt])

  const reload = useCallback(() => setAttempt((n) => n + 1), [])

  // While a worker writes a report, the page follows it until it is ready (UC-9.1 step 4).
  const writing = data?.rows.some((row) => row.status === "generating") ?? false
  useEffect(() => {
    if (!writing) return
    const timer = setInterval(reload, POLL)
    return () => clearInterval(timer)
  }, [writing, reload])

  async function act(id: string, what: () => Promise<unknown>, done: string) {
    setBusy(id)
    try {
      await what()
      toast.success(done)
      reload()
    } catch (failed) {
      toast.error(failed instanceof ApiError ? failed.message : "That didn't work. Try again.")
    } finally {
      setBusy(null)
    }
  }

  const reports = data?.rows ?? []
  const schedules = data?.schedules ?? []

  return (
    <>
      <PageHeader
        title="Reports"
        description="Executive and technical reports of your targets, generated by Sentra and kept with their checksum."
        action={
          canGenerate ? (
            <div className="flex flex-wrap gap-2">
              <Button
                variant="outline"
                className="h-9"
                onClick={() => setDialog({ scheduled: true })}
              >
                Schedule report
              </Button>
              <Button className="h-9 hover:bg-primary-hover" onClick={() => setDialog({})}>
                Generate report
              </Button>
            </div>
          ) : undefined
        }
      />

      {error && (
        <Alert variant="destructive" role="alert">
          <AlertDescription className="flex items-center justify-between gap-4">
            The reports could not be loaded.
            <Button variant="outline" size="sm" onClick={reload}>
              Try again
            </Button>
          </AlertDescription>
        </Alert>
      )}

      {!data && !error && (
        <div className="space-y-2" role="status" aria-label="Loading the reports">
          <Skeleton className="h-10 w-full" />
          <Skeleton className="h-56 w-full" />
        </div>
      )}

      {data && (
        <Tabs defaultValue="reports">
          <TabsList className="mb-4">
            <TabsTrigger value="reports">Reports ({reports.length})</TabsTrigger>
            <TabsTrigger value="schedules">Schedules ({schedules.length})</TabsTrigger>
          </TabsList>

          <TabsContent
            value="reports"
            className="mt-0 rounded-[10px] focus-visible:ring-2 focus-visible:ring-ring focus-visible:outline-none"
          >
            {reports.length === 0 ? (
              <EmptyState
                title="No report yet"
                description="Generate an executive report for the organization, or a technical one for a target or a campaign run."
                action={
                  canGenerate ? (
                    <Button className="h-9 hover:bg-primary-hover" onClick={() => setDialog({})}>
                      Generate report
                    </Button>
                  ) : undefined
                }
              />
            ) : (
              <section aria-labelledby="reports" className="min-w-0 rounded-[10px] border bg-card">
                <h2 id="reports" className="sr-only">
                  Reports
                </h2>
                <Table
                  container={{
                    tabIndex: 0,
                    role: "group",
                    "aria-label": "Reports",
                    className:
                      "rounded-[7px] focus-visible:ring-2 focus-visible:ring-ring focus-visible:outline-none",
                  }}
                >
                  <TableHeader className="bg-muted">
                    <TableRow>
                      <TableHead scope="col" className="text-xs">
                        Report
                      </TableHead>
                      <TableHead scope="col" className="text-xs">
                        Type
                      </TableHead>
                      <TableHead scope="col" className="text-xs">
                        Scope
                      </TableHead>
                      <TableHead scope="col" className="text-xs">
                        Period
                      </TableHead>
                      <TableHead scope="col" className="text-xs">
                        Format
                      </TableHead>
                      <TableHead scope="col" className="text-xs">
                        Created
                      </TableHead>
                      <TableHead scope="col" className="text-xs">
                        Status
                      </TableHead>
                      <TableHead scope="col" className="text-xs">
                        <span className="sr-only">Download</span>
                      </TableHead>
                    </TableRow>
                  </TableHeader>
                  <TableBody>
                    {reports.map((report) => (
                      <TableRow key={report.id}>
                        <TableCell className="max-w-xs whitespace-normal">
                          <span className="block text-[13px] font-medium">{report.code}</span>
                          <span className="block text-[13px]">{report.title}</span>
                          {report.schedule && (
                            <span className="block text-xs text-muted-foreground">
                              Schedule “{report.schedule}”
                            </span>
                          )}
                        </TableCell>
                        <TableCell className="text-[13px]">{TYPE_LABEL[report.type]}</TableCell>
                        <TableCell className="max-w-[12rem] text-[13px] whitespace-normal">
                          {scopeText(report)}
                        </TableCell>
                        <TableCell className="text-[13px] whitespace-nowrap">
                          {report.period_from && report.period_to
                            ? `${formatDate(report.period_from)} – ${formatDate(report.period_to)}`
                            : "—"}
                        </TableCell>
                        <TableCell className="text-[13px] uppercase">{report.format}</TableCell>
                        <TableCell className="text-[13px]">
                          <span className="block whitespace-nowrap">
                            {formatDateTime(report.created_at)}
                          </span>
                          <span className="block text-xs text-muted-foreground">
                            {report.requested_by ?? "Sentra"}
                          </span>
                        </TableCell>
                        <TableCell>
                          <StatusChip report={report} />
                          {report.message && (
                            <span className="mt-1 block max-w-[14rem] text-xs whitespace-normal text-muted-foreground">
                              {report.message}
                            </span>
                          )}
                        </TableCell>
                        <TableCell className="text-right">
                          {report.status === "ready" && report.checksum ? (
                            <Tooltip>
                              <TooltipTrigger asChild>
                                <Button asChild variant="outline" size="sm" className="h-8">
                                  <a href={downloadUrl(report.code)} download>
                                    <Download className="size-3.5" aria-hidden="true" />
                                    Download
                                  </a>
                                </Button>
                              </TooltipTrigger>
                              <TooltipContent>
                                SHA-256 {report.checksum.slice(0, 16)}…
                              </TooltipContent>
                            </Tooltip>
                          ) : (
                            <span className="text-xs text-muted-foreground">No file</span>
                          )}
                        </TableCell>
                      </TableRow>
                    ))}
                  </TableBody>
                </Table>
                <p className="border-t p-3 text-[13px] text-muted-foreground">
                  Reports open only after login. Scheduled reports are delivered as links, never as
                  attachments.
                </p>
              </section>
            )}
          </TabsContent>

          <TabsContent
            value="schedules"
            className="mt-0 rounded-[10px] focus-visible:ring-2 focus-visible:ring-ring focus-visible:outline-none"
          >
            {schedules.length === 0 ? (
              <EmptyState
                title="No schedule yet"
                description="A schedule produces a report after every campaign run of a target, weekly or monthly, and tells its recipients with a link."
                action={
                  canGenerate ? (
                    <Button
                      className="h-9 hover:bg-primary-hover"
                      onClick={() => setDialog({ scheduled: true })}
                    >
                      Schedule report
                    </Button>
                  ) : undefined
                }
              />
            ) : (
              <section
                aria-labelledby="schedules"
                className="min-w-0 rounded-[10px] border bg-card"
              >
                <h2 id="schedules" className="sr-only">
                  Schedules
                </h2>
                <Table
                  container={{
                    tabIndex: 0,
                    role: "group",
                    "aria-label": "Schedules",
                    className:
                      "rounded-[7px] focus-visible:ring-2 focus-visible:ring-ring focus-visible:outline-none",
                  }}
                >
                  <TableHeader className="bg-muted">
                    <TableRow>
                      <TableHead scope="col" className="text-xs">
                        Schedule
                      </TableHead>
                      <TableHead scope="col" className="text-xs">
                        Scope
                      </TableHead>
                      <TableHead scope="col" className="text-xs">
                        Frequency
                      </TableHead>
                      <TableHead scope="col" className="text-xs">
                        Recipients
                      </TableHead>
                      <TableHead scope="col" className="text-xs">
                        Next report
                      </TableHead>
                      <TableHead scope="col" className="text-xs">
                        <span className="sr-only">Actions</span>
                      </TableHead>
                    </TableRow>
                  </TableHeader>
                  <TableBody>
                    {schedules.map((schedule) => (
                      <TableRow key={schedule.id}>
                        <TableCell className="max-w-xs whitespace-normal">
                          <span className="block text-[13px] font-medium">{schedule.name}</span>
                          <span className="block text-xs text-muted-foreground">
                            {TYPE_LABEL[schedule.type]} · {schedule.format.toUpperCase()} ·{" "}
                            {schedule.status === "paused" ? "Paused" : "Active"}
                          </span>
                        </TableCell>
                        <TableCell className="max-w-[12rem] text-[13px] whitespace-normal">
                          {scopeText(schedule)}
                        </TableCell>
                        <TableCell className="text-[13px]">
                          {FREQUENCY_LABEL[schedule.frequency]}
                        </TableCell>
                        <TableCell className="max-w-[12rem] text-[13px] whitespace-normal">
                          {schedule.recipients.map((one) => one.name).join(", ") || "—"}
                        </TableCell>
                        <TableCell className="text-[13px] whitespace-nowrap">
                          {schedule.status === "paused"
                            ? "Paused"
                            : schedule.next_run_at
                              ? formatDate(schedule.next_run_at)
                              : "After the next campaign run"}
                        </TableCell>
                        <TableCell className="text-right">
                          {canGenerate && (
                            <span className="flex flex-wrap justify-end gap-2">
                              <Button
                                variant="outline"
                                size="sm"
                                className="h-8"
                                aria-label={`Edit ${schedule.name}`}
                                onClick={() => setDialog({ schedule })}
                              >
                                Edit
                              </Button>
                              <Button
                                variant="outline"
                                size="sm"
                                className="h-8"
                                disabled={busy === schedule.id}
                                aria-label={`Run ${schedule.name} now`}
                                onClick={() =>
                                  act(
                                    schedule.id,
                                    () => runSchedule(schedule.id),
                                    "Sentra is writing the report.",
                                  )
                                }
                              >
                                Run now
                              </Button>
                              <Button
                                variant="outline"
                                size="sm"
                                className="h-8"
                                disabled={busy === schedule.id}
                                aria-label={`${schedule.status === "paused" ? "Resume" : "Pause"} ${schedule.name}`}
                                onClick={() =>
                                  act(
                                    schedule.id,
                                    () =>
                                      changeSchedule(schedule.id, {
                                        status: schedule.status === "paused" ? "active" : "paused",
                                      }),
                                    schedule.status === "paused"
                                      ? "The schedule is active again."
                                      : "The schedule is paused.",
                                  )
                                }
                              >
                                {schedule.status === "paused" ? "Resume" : "Pause"}
                              </Button>
                              <Button
                                variant="outline"
                                size="sm"
                                className="h-8"
                                aria-label={`Delete ${schedule.name}`}
                                onClick={() => setDeleting(schedule)}
                              >
                                Delete
                              </Button>
                            </span>
                          )}
                        </TableCell>
                      </TableRow>
                    ))}
                  </TableBody>
                </Table>
                <p className="border-t p-3 text-[13px] text-muted-foreground">
                  A change applies from the next report. Deleting a schedule keeps the reports it
                  has already produced.
                </p>
              </section>
            )}
          </TabsContent>
        </Tabs>
      )}

      <ReportDialog
        open={dialog !== null}
        members={data?.members ?? []}
        schedule={dialog?.schedule ?? null}
        startScheduled={dialog?.scheduled}
        onClose={() => setDialog(null)}
        onDone={reload}
      />

      {/* UC-9.2, 4a: the schedule goes, the reports it produced stay — so it is asked first. */}
      <Dialog open={deleting !== null} onOpenChange={(next) => !next && setDeleting(null)}>
        <DialogContent className="sm:max-w-[480px]">
          <DialogHeader>
            <DialogTitle>Delete this schedule?</DialogTitle>
            <DialogDescription>
              “{deleting?.name}” stops producing reports and its recipients hear nothing more. The
              reports it has already produced stay in the list and can still be downloaded.
            </DialogDescription>
          </DialogHeader>
          <DialogFooter>
            <DialogClose asChild>
              <Button variant="outline" className="h-9">
                Keep it
              </Button>
            </DialogClose>
            <Button
              variant="destructive"
              className="h-9"
              disabled={busy === deleting?.id}
              onClick={() => {
                const schedule = deleting
                if (!schedule) return
                setDeleting(null)
                act(
                  schedule.id,
                  () => deleteSchedule(schedule.id),
                  "The schedule is deleted. Its reports stay.",
                )
              }}
            >
              Delete schedule
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>
    </>
  )
}
