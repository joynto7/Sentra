"""Scheduled reports (FR-9.2, UC-9.2 Schedule Report).

A schedule says what to produce, how often and who gets the link. The reports it produces are
stored like the ones generated by hand (quality requirement 5) and are delivered as links that
need a login, never as attachments (quality requirement 6).
"""

import uuid
from calendar import monthrange
from datetime import UTC, datetime, timedelta

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.core import audit
from app.core.errors import FieldValidationError, NotFoundError
from app.core.tenancy import scoped_select
from app.modules.m01_users.models import Membership, MembershipStatus, User
from app.modules.m05_campaigns.models import CampaignRun
from app.modules.m09_reporting import reports
from app.modules.m09_reporting.models import (
    Report,
    ReportSchedule,
    ScheduleFrequency,
    ScheduleStatus,
)


def _now() -> datetime:
    return datetime.now(UTC)


def next_time(frequency: str, after: datetime) -> datetime | None:
    """When the next report of this schedule is due. A schedule that follows the campaign runs has
    no time of its own: its trigger is the end of a run (step 2)."""
    if frequency == ScheduleFrequency.WEEKLY:
        return after + timedelta(days=7)
    if frequency == ScheduleFrequency.MONTHLY:
        # The first of the next month, at the time of day the schedule was saved.
        days = monthrange(after.year, after.month)[1]
        first = (after + timedelta(days=days - after.day + 1)).replace(day=1)
        return first
    return None


def members(db: Session, organization_id: uuid.UUID) -> dict[uuid.UUID, str]:
    """Who may be a recipient: the active members of the organization (FR-1.6, quality
    requirement 3). Reports never leave the organization."""
    rows = db.execute(
        select(User.id, User.name)
        .join(Membership, Membership.user_id == User.id)
        .where(
            Membership.organization_id == organization_id,
            Membership.status == MembershipStatus.ACTIVE,
        )
    ).all()
    return {one[0]: one[1] for one in rows}


def _recipients(db: Session, organization_id: uuid.UUID, wanted: list[uuid.UUID]) -> list[str]:
    """3a1: an address that doesn't belong to a member is refused; the rest are kept in order."""
    allowed = members(db, organization_id)
    unknown = [one for one in wanted if one not in allowed]
    if unknown:
        raise FieldValidationError(
            "recipient_ids", "Reports go only to members of this organization."
        )
    if not wanted:
        raise FieldValidationError("recipient_ids", "Choose at least one recipient.")
    return [str(one) for one in dict.fromkeys(wanted)]


def recipients_of(db: Session, schedule_id: uuid.UUID) -> list[uuid.UUID]:
    """6a1: whoever left the organization since is no longer a recipient."""
    schedule = db.get(ReportSchedule, schedule_id)
    if schedule is None:
        return []
    allowed = members(db, schedule.organization_id)
    return [uuid.UUID(one) for one in schedule.recipient_ids if uuid.UUID(one) in allowed]


def create(
    db: Session,
    *,
    organization_id: uuid.UUID,
    user: User,
    name: str,
    spec: reports.Spec,
    frequency: str,
    recipient_ids: list[uuid.UUID],
) -> ReportSchedule:
    """UC-9.2 steps 1-4: the schedule, with the date of its next report."""
    reports.check(db, organization_id, spec)
    if frequency not in tuple(ScheduleFrequency):
        raise FieldValidationError("frequency", "Choose how often the report is produced.")
    if frequency == ScheduleFrequency.AFTER_EACH_RUN and spec.target_id is None:
        raise FieldValidationError(
            "target_id", "A report after every campaign run needs a target to follow."
        )
    if not name.strip():
        raise FieldValidationError("name", "Give the schedule a name.")
    now = _now()
    schedule = ReportSchedule(
        organization_id=organization_id,
        name=name.strip()[:120],
        type=spec.type,
        scope=spec.scope,
        target_id=spec.target_id,
        category=spec.category,
        period_days=spec.period_days,
        format=spec.format,
        frequency=frequency,
        recipient_ids=_recipients(db, organization_id, recipient_ids),
        created_by_id=user.id,
        next_run_at=next_time(frequency, now),
    )
    db.add(schedule)
    db.flush()
    _record(db, schedule, user, "report_schedule.created", f"Scheduled {schedule.name}")
    db.commit()
    return schedule


def update(
    db: Session,
    organization_id: uuid.UUID,
    user: User,
    schedule_id: uuid.UUID,
    *,
    name: str | None = None,
    recipient_ids: list[uuid.UUID] | None = None,
    frequency: str | None = None,
    status: str | None = None,
) -> ReportSchedule:
    """4a1: a change applies from the next report, and is recorded."""
    schedule = row(db, organization_id, schedule_id)
    if name is not None:
        schedule.name = name.strip()[:120] or schedule.name
    if recipient_ids is not None:
        schedule.recipient_ids = _recipients(db, organization_id, recipient_ids)
    if frequency is not None and frequency != schedule.frequency:
        if frequency not in tuple(ScheduleFrequency):
            raise FieldValidationError("frequency", "Choose how often the report is produced.")
        schedule.frequency = frequency
        schedule.next_run_at = next_time(frequency, _now())
    if status is not None:
        if status not in tuple(ScheduleStatus):
            raise FieldValidationError("status", "A schedule is active or paused.")
        schedule.status = status
        if status == ScheduleStatus.ACTIVE and schedule.next_run_at is None:
            schedule.next_run_at = next_time(schedule.frequency, _now())
    _record(db, schedule, user, "report_schedule.changed", f"Changed the schedule {schedule.name}")
    db.commit()
    return schedule


def delete(db: Session, organization_id: uuid.UUID, user: User, schedule_id: uuid.UUID) -> None:
    """4a: the schedule is removed; the reports it already produced stay (quality requirement 5)."""
    schedule = row(db, organization_id, schedule_id)
    name = schedule.name
    # The reports it produced stay; their schedule_id is set to NULL by the database.
    _record(db, schedule, user, "report_schedule.deleted", f"Deleted the schedule {name}")
    db.delete(schedule)
    db.commit()


def row(db: Session, organization_id: uuid.UUID, schedule_id: uuid.UUID) -> ReportSchedule:
    schedule = db.scalar(
        scoped_select(ReportSchedule, organization_id).where(ReportSchedule.id == schedule_id)
    )
    if schedule is None:
        raise NotFoundError("Schedule not found.")
    return schedule


def _record(db: Session, schedule: ReportSchedule, user: User, action: str, summary: str) -> None:
    audit.record(
        db,
        organization_id=schedule.organization_id,
        actor=user,
        action=action,
        summary=f"{summary} ({schedule.frequency}, {schedule.format.upper()})",
        item=audit.Item("report_schedule", schedule.id, schedule.name),
        details={
            "frequency": schedule.frequency,
            "type": schedule.type,
            "recipients": len(schedule.recipient_ids),
        },
    )


def schedules_of(db: Session, organization_id: uuid.UUID) -> list[ReportSchedule]:
    """The organization's schedules, the newest first (the "Schedules" tab of Screen 52)."""
    return list(
        db.scalars(
            scoped_select(ReportSchedule, organization_id).order_by(
                ReportSchedule.created_at.desc()
            )
        )
    )


# ---------------------------------------------------------------- what starts a scheduled report


def _spec(schedule: ReportSchedule) -> reports.Spec:
    return reports.Spec(
        type=schedule.type,
        scope=schedule.scope,
        format=schedule.format,
        target_id=schedule.target_id,
        period_days=schedule.period_days,
        category=schedule.category,
    )


def run_schedule(db: Session, schedule: ReportSchedule, at: datetime | None = None) -> Report:
    """Step 5: the schedule's report, made like one asked for by hand, and told to its recipients
    with a link (step 6)."""
    now = at or _now()
    report = reports.request(
        db,
        organization_id=schedule.organization_id,
        user=db.get(User, schedule.created_by_id) if schedule.created_by_id else None,
        spec=_spec(schedule),
        schedule_id=schedule.id,
    )
    schedule.last_run_at = now
    if schedule.frequency != ScheduleFrequency.AFTER_EACH_RUN:
        schedule.next_run_at = next_time(schedule.frequency, now)
    db.commit()
    return report


def due(db: Session, at: datetime | None = None) -> list[Report]:
    """The reports that are due now. The scheduler of FR-5.3 calls this; until J-S3-01 is merged
    it is called by hand and by its tests."""
    now = at or _now()
    made = []
    for schedule in db.scalars(
        select(ReportSchedule).where(
            ReportSchedule.status == ScheduleStatus.ACTIVE,
            ReportSchedule.next_run_at.is_not(None),
            ReportSchedule.next_run_at <= now,
        )
    ).all():
        made.append(run_schedule(db, schedule, now))
    return made


def after_run(db: Session, run: CampaignRun) -> list[Report]:
    """Step 2, "after every campaign run of the target": the run has ended, so its schedules
    produce their report. M9's hook calls it through the run engine's extension points."""
    made = []
    for schedule in db.scalars(
        select(ReportSchedule).where(
            ReportSchedule.organization_id == run.organization_id,
            ReportSchedule.target_id == run.target_id,
            ReportSchedule.frequency == ScheduleFrequency.AFTER_EACH_RUN,
            ReportSchedule.status == ScheduleStatus.ACTIVE,
        )
    ).all():
        made.append(run_schedule(db, schedule))
    return made
